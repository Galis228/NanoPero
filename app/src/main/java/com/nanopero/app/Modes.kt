package com.nanopero.app

import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.rounded.*
import androidx.compose.ui.graphics.vector.ImageVector

enum class Mode(val title: String, val icon: ImageVector, val inChips: Boolean = true) {
    FIX("Исправить ошибки", Icons.Rounded.Spellcheck),
    REWRITE("Переписать лучше", Icons.Rounded.AutoFixHigh),
    SHORT("Короче", Icons.Rounded.ShortText),
    FORMAL("Деловой стиль", Icons.Rounded.BusinessCenter),
    FRIENDLY("Дружелюбно", Icons.Rounded.EmojiEmotions),
    TRANSLATE("Перевести", Icons.Rounded.Translate),
    SIMPLE("Объяснить проще", Icons.Rounded.Lightbulb),
    SUMMARY("Главное", Icons.Rounded.FormatListBulleted),
    REPLY("Варианты ответа", Icons.Rounded.Reply),
    SCAM("Проверить на развод", Icons.Rounded.GppMaybe),
    PLAN("План из хаоса", Icons.Rounded.Checklist),
    CARDS("Карточки", Icons.Rounded.Style),
    EVENT("В календарь", Icons.Rounded.Event),
    CUSTOM("Пресет", Icons.Rounded.Tune, inChips = false);
}

/** Пользовательский пресет: своя инструкция для текста. */
data class Preset(val id: Long, val name: String, val instruction: String)

object Prompts {
    private const val ONLY = "Выведи только результат, без вступлений, пояснений и кавычек."

    const val SYSTEM_TEXT = "Ты — НаноПеро, внимательный редактор и помощник по работе с текстом. Ты работаешь офлайн на телефоне. " +
            "Строго выполняй инструкцию. Отвечай только результатом: без вступлений вроде «Вот текст», без пояснений, " +
            "без markdown-разметки и без кавычек вокруг ответа. Сохраняй язык исходного текста, если не сказано иное. " +
            "Не выдумывай факты, которых нет в тексте."

    const val SYSTEM_CHAT = "Ты — НаноПеро, дружелюбный и точный ассистент, который работает офлайн прямо на телефоне. " +
            "Отвечай по существу, ясно и без воды, на языке пользователя (по умолчанию — по-русски). " +
            "Для списков используй короткие пункты. Если не уверен или не знаешь — честно так и скажи, не выдумывай."

    /** Точные задачи — низкая температура, творческие — выше. */
    fun temperature(m: Mode): Float = when (m) {
        Mode.FIX, Mode.EVENT -> 0.1f
        Mode.TRANSLATE, Mode.SCAM -> 0.2f
        Mode.SUMMARY, Mode.SHORT, Mode.PLAN -> 0.3f
        Mode.SIMPLE, Mode.FORMAL, Mode.CARDS -> 0.4f
        Mode.REWRITE, Mode.FRIENDLY, Mode.CUSTOM -> 0.6f
        Mode.REPLY -> 0.8f
    }

    fun build(mode: Mode, text: String, s: Settings, preset: Preset? = null): String = when (mode) {
        Mode.FIX -> "Исправь орфографические, пунктуационные и грамматические ошибки в тексте. " +
                "Сохрани язык, смысл и стиль автора. $ONLY\n\nТекст:\n$text"
        Mode.REWRITE -> "Перепиши текст так, чтобы он читался легко и естественно. " +
                "Сохрани язык оригинала и весь смысл. $ONLY\n\nТекст:\n$text"
        Mode.SHORT -> "Сократи текст примерно вдвое, сохранив главное. Язык оригинала. $ONLY\n\nТекст:\n$text"
        Mode.FORMAL -> "Перепиши текст в вежливом деловом стиле, подходящем для письма коллеге или клиенту. " +
                "Язык оригинала. $ONLY\n\nТекст:\n$text"
        Mode.FRIENDLY -> "Перепиши текст в тёплом дружелюбном неформальном тоне. Язык оригинала. $ONLY\n\nТекст:\n$text"
        Mode.TRANSLATE -> "Переведи текст на язык: ${s.translateTo}. Если текст уже на этом языке — " +
                "переведи его на русский. Передай смысл естественно, а не дословно. $ONLY\n\nТекст:\n$text"
        Mode.SIMPLE -> "Объясни простыми словами, о чём этот текст и что он значит для читателя. " +
                "Убери канцелярит и термины. Ответь по-русски, 3–6 предложений.\n\nТекст:\n$text"
        Mode.SUMMARY -> summary(text)
        Mode.REPLY -> "Это входящее сообщение. Предложи 3 коротких варианта ответа на него разными тонами " +
                "(нейтральный, тёплый, краткий). Язык сообщения. Формат: каждый вариант с новой строки, " +
                "начиная с «1) », «2) », «3) ». $ONLY\n\nСообщение:\n$text"
        Mode.SCAM -> "Оцени, похоже ли это сообщение на мошенничество, фишинг или развод " +
                "(срочность, просьба перевести деньги, код из SMS, данные карты, подозрительные ссылки, " +
                "«ваша карта заблокирована», выигрыши, фейковые доставки). Ответь по-русски в формате:\n" +
                "Вердикт: 🟢 безопасно / 🟡 подозрительно / 🔴 похоже на развод\n" +
                "Признаки: 1–3 коротких пункта\nСовет: одно предложение.\n\nСообщение:\n$text"
        Mode.PLAN -> "Это поток мыслей и дел. Преврати его в понятный план: сгруппируй задачи, " +
                "отметь самое срочное, убери повторы. Формат — список задач, каждая с новой строки, " +
                "начиная с «☐ », самые важные сверху с пометкой «❗». Язык оригинала. $ONLY\n\nТекст:\n$text"
        Mode.CARDS -> "Сделай из текста 5 карточек для запоминания. Формат строго:\n" +
                "В: вопрос\nО: короткий ответ\n(пустая строка между карточками). Язык оригинала. $ONLY\n\nТекст:\n$text"
        Mode.EVENT -> "Извлеки из текста событие для календаря. Сегодня ${CalendarHelper.today()}. " +
                "Относительные даты («завтра», «в четверг») переведи в точную дату. " +
                "Ответь строго одним JSON-объектом без markdown.\n" +
                "Пример: текст «созвон с Олей в пятницу в 15:30 в зуме» → " +
                "{\"title\":\"Созвон с Олей\",\"date\":\"2026-11-27\",\"time\":\"15:30\",\"duration_min\":60,\"location\":\"Zoom\"}\n" +
                "Если времени нет — \"time\":\"\". Если места нет — \"location\":\"\".\n\nТекст:\n$text"
        Mode.CUSTOM -> "${preset?.instruction?.ifBlank { null } ?: "Улучши этот текст."}\n$ONLY\n\nТекст:\n$text"
    }

    fun summary(text: String) = "Выдели 3–5 главных тезисов текста. Каждый тезис — одна короткая строка, " +
            "начинающаяся с «• ». Ответь по-русски. $ONLY\n\nТекст:\n$text"

    fun partSummary(text: String) = "Кратко перескажи этот фрагмент в 2–4 предложениях, сохранив факты, " +
            "имена, цифры и договорённости. Ответь по-русски. $ONLY\n\nФрагмент:\n$text"

    fun chat(app: String, title: String, lines: String) =
        "Это сообщения из «$app», чат/отправитель «$title». Сделай сводку в 1–3 коротких пунктах: " +
                "что важного, кто что просит, нужен ли ответ. Каждый пункт с «• ». Ответь по-русски. $ONLY\n\n" +
                "Сообщения:\n$lines"

    fun day(parts: String) = "Это сводки переписок за день. Выдели 3–5 самых важных пунктов дня: " +
            "дела, просьбы, договорённости, на что нужно ответить. Каждый пункт с «• ». Ответь по-русски. $ONLY\n\n" +
            "Сводки:\n$parts"

    fun week(entries: String) = "Это записи дневника за неделю. Сделай короткие итоги недели по-русски:\n" +
            "🔹 Главное (2–3 пункта: о чём думал, что произошло)\n✅ Сделано (кратко)\n" +
            "☐ Не закрыто (открытые задачи)\n💡 Совет на следующую неделю (одно предложение).\n$ONLY\n\nЗаписи:\n$entries"

    fun diary(text: String) = "Это голосовая заметка (расшифровка речи, могут быть ошибки распознавания). " +
            "Сегодня ${CalendarHelper.today()}. Ответь строго одним JSON-объектом без markdown:\n" +
            "{\"title\":\"короткий заголовок 2–5 слов\",\"summary\":\"1–2 предложения сути\"," +
            "\"tags\":[\"1–4 тега одним словом в нижнем регистре\"],\"tasks\":[\"конкретные дела из заметки, если есть\"]}\n" +
            "Пример: «надо завтра купить корм коту и позвонить маме, а ещё придумал идею для приложения про привычки» → " +
            "{\"title\":\"Дела и идея приложения\",\"summary\":\"Купить корм коту, позвонить маме; идея приложения про привычки.\"," +
            "\"tags\":[\"дела\",\"идеи\",\"семья\"],\"tasks\":[\"Купить корм коту\",\"Позвонить маме\"]}\n" +
            "Если дел нет — \"tasks\":[]. Пиши на языке заметки.\n\n" +
            "Заметка:\n$text"
}
